-- `style_mood` 의 기본값을 'amekaji' 에서 NULL 로 바꾼다.
--
-- `20260521000002` 가 컬럼을 `DEFAULT 'amekaji'` 로 만들었고, 등록 경로는 이
-- 컬럼을 한 번도 쓰지 않는다(`clothing_repo::create_clothing` 의 INSERT 에 없다).
-- 그래서 사용자가 올리는 모든 아이템은 실제로 무엇이든 'amekaji' 가 된다.
--
-- 이 상태에서 'amekaji' 는 두 가지를 동시에 뜻한다.
--
--   1. 사용자가 고른 장르가 아메카지다.
--   2. 장르가 지정된 적이 없다.
--
-- 후보 조회는 2번으로 읽어야 새 장르에 옷이 잡히고, 장르 칩은 1번으로 읽어야
-- 아메카지가 아메카지다. 한 값에 두 뜻을 담아두면 나중에 실제로 아메카지를
-- 태깅하는 경로가 생겼을 때 그 아이템이 '미분류' 로 취급돼 모든 장르로 샌다.
--
-- 그래서 뜻을 갈라 둔다. NULL = 미분류, 값이 있으면 = 그 장르로 지정됨.
-- 미분류 아이템을 어느 장르 후보로 볼지는 아이템 속성으로 판단한다
-- (`clothing_repo::genre_predicate`).
--
-- 여러 번 실행해도 결과가 같다.

-- ─── 1. 앞으로 들어오는 아이템 ───
-- 등록 경로가 이 컬럼을 채우기 전까지, 새 아이템은 '아메카지' 가 아니라 '미분류'다.
ALTER TABLE clothing MODIFY COLUMN style_mood VARCHAR(50) DEFAULT NULL;

-- ─── 2. 이미 들어와 있는 아이템 ───
--
-- 남성 아이템 140벌은 전부 'amekaji' 인데, 이건 분류의 결과가 아니라 기본값이
-- 그대로 남은 것이다. `20260521000002` 가 그 시점의 아이템 전체를 한 줄로
-- 태깅했고(`UPDATE clothing SET gender='male', style_mood='amekaji'`), 그 뒤로
-- 이 값을 바꾸는 경로는 없었다. 그러니 이 행들은 '아메카지로 판단됨'이 아니라
-- '판단된 적 없음'이다. 그대로 NULL 로 옮긴다.
--
-- 여성 아이템은 시드가 장르를 하나씩 지정해 넣었으므로 'amekaji' 인 행이 없고,
-- 이 UPDATE 에 걸리지 않는다. `20260910000006` 이 넣은 남성 스포티/아웃도어
-- 아이템도 장르가 지정돼 있어 걸리지 않는다.
UPDATE clothing SET style_mood = NULL WHERE style_mood = 'amekaji';
