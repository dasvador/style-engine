//! 마이그레이션이 바뀌면 바이너리를 다시 빌드하게 만든다.
//!
//! `main.rs` 의 `sqlx::migrate!("./migrations")` 는 마이그레이션을 **컴파일 시점에**
//! 바이너리 안으로 읽어 넣는다. 그런데 cargo 는 `.sql` 파일을 소스로 보지 않으므로,
//! 마이그레이션을 새로 추가해도 재빌드가 걸리지 않는다. 그러면 `cargo run` 이
//! 0.3 초 만에 "Finished" 를 찍고 **예전 마이그레이션 목록을 담은 바이너리**가
//! 그대로 뜬다. 서버는 정상 기동하고, 새 마이그레이션만 조용히 실행되지 않는다.
//!
//! 실제로 2026-09-10 에 이 일이 있었다. 여성 계절 백필(`20260910000009`)과
//! 워크웨어 여름 보정(`20260910000010`)을 넣고 재시작했는데 `_sqlx_migrations`
//! 에 두 건이 올라오지 않았다. 아무 오류도 나지 않아서, 계절 데이터를 직접
//! 세어 보기 전까지는 적용된 줄 알았다.
//!
//! 아래 한 줄이 그 경로를 막는다. cargo 가 `migrations/` 를 감시 대상으로 잡아
//! 파일이 추가·수정되면 크레이트를 다시 컴파일한다.

fn main() {
    println!("cargo:rerun-if-changed=migrations");
}
