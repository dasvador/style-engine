/** 색 이름 하나(`레드/핑크` 처럼 둘이면 둘)의 점 색. 모르면 빈 배열. */
export function swatchesFor(color: string | null | undefined): string[] {
  if (!color) return [];
  return color
    .split('/')
    .map((part) => SWATCHES.find(([name]) => part.includes(name))?.[1])
    .filter((hex): hex is string => Boolean(hex));
}
